const vm=require('node:vm');
const fs=require('node:fs');
const assert=require('node:assert/strict');
const {setTimeout:delay}=require('node:timers/promises');
(async()=>{
  const input={value:'성수',isConnected:true,focus(){}},list={innerHTML:'',isConnected:true},requests=[];
  const kakao={maps:{services:{Status:{OK:'OK',ZERO_RESULT:'ZERO'},Places:class{keywordSearch(keyword,callback,options){requests.push({keyword,callback,options});}}}}};
  const context=vm.createContext({setTimeout,clearTimeout,console,loadKakaoSdk:async()=>kakao,esc:s=>String(s),document:{querySelector:s=>s==='#place-search'?input:s==='#place-results'?list:null}});
  vm.runInContext(fs.readFileSync('composer.js','utf8'),context);
  const run=source=>vm.runInContext(source,context);
  run("schedulePlaceSearch(document.querySelector('#place-search'))");
  input.value='성수 카페';
  run("schedulePlaceSearch(document.querySelector('#place-search'))");
  await delay(350);
  assert.equal(requests.length,2);
  assert.ok(requests.every(r=>r.keyword==='성수 카페'));
  input.value='연남';
  run("schedulePlaceSearch(document.querySelector('#place-search'))");
  for(const r of requests)r.callback([{id:'old',place_name:'오래된 결과',category_group_code:'CE7'}],'OK');
  await delay(0);
  assert.doesNotMatch(list.innerHTML,/오래된 결과/);
  await delay(350);
  assert.equal(requests.length,4);
  for(const r of requests.slice(2))r.callback(Array.from({length:5},(_,i)=>({id:r.options.category_group_code+i,place_name:'추천 장소 '+i,road_address_name:'서울',category_name:'음식점 > 카페',category_group_code:r.options.category_group_code})),'OK');
  await delay(0);
  assert.equal((list.innerHTML.match(/data-choose-place/g)||[]).length,5);
  input.value='';run("schedulePlaceSearch(document.querySelector('#place-search'))");
  assert.equal(list.innerHTML,'');
  await delay(350);
  assert.equal(requests.length,4);
  run(`
    let removedPins=0;
    window={kakao:{maps:{LatLng:class{constructor(lat,lon){this.lat=lat;this.lon=lon}},Marker:class{constructor(options){this.options=options}setMap(map){if(map===null)removedPins++}}}}};
    discoveryMap={setLevel(level){this.level=level},panTo(position){this.position=position}};
    discoveryMarkers=Array.from({length:5},()=>({setMap(map){if(map===null)removedPins++}}));
    showSelectedDiscoveryPlace({name:'선택한 식당',lat:37.5,lon:127});
  `);
  assert.equal(run('removedPins'),5);
  assert.equal(run('discoveryMarkers.length'),1);
  assert.equal(run('discoveryMarkers[0].options.title'),'선택한 식당');
  run("showSelectedDiscoveryPlace({name:'다른 식당',lat:35.1,lon:129.1})");
  assert.equal(run('removedPins'),6);
  assert.equal(run('discoveryMarkers.length'),1);
  assert.equal(run('discoveryMap.position.lat'),35.1);
  console.log('PASS: debounced automatic search, latest query only, maximum five suggestions, clearing query');
  console.log('PASS: selecting a place removes every previous result pin and leaves one selected pin');
})().catch(error=>{console.error(error);process.exitCode=1;});
