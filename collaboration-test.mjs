import assert from 'node:assert/strict';
import {mkdtemp,readFile,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import path from 'node:path';
import {CollaborationStore,createCollaborationApi} from './collaboration-store.mjs';
const parent=path.resolve(tmpdir()),directory=await mkdtemp(path.join(parent,'micheulcheop-collab-test-'));
assert.ok(path.resolve(directory).startsWith(parent+path.sep));
const file=path.join(directory,'store.json'),origin='http://localhost:5174';
try{
  let clock=Date.now();const store=await new CollaborationStore(file).load();
  const users={owner:{id:'owner',nickname:'가은',photo:''},friend:{id:'friend',nickname:'친구',photo:''},stranger:{id:'stranger',nickname:'외부인',photo:''}};
  const api=createCollaborationApi({store,getUser:req=>users[req.headers.user],origin,now:()=>clock,onError:error=>console.error(error)});
  async function call(route,{user='owner',method='GET',body,requestOrigin=origin,handler=api}={}){
    const req={method,headers:{user,origin:requestOrigin},async *[Symbol.asyncIterator](){if(body!==undefined)yield Buffer.from(JSON.stringify(body));}};
    const res={writeHead(status){this.status=status},end(value){this.body=JSON.parse(value)}};
    assert.equal(await handler(req,res,new URL('/api/collab'+route,origin)),true);return res;
  }
  const notebook={name:'함께 먹는 수첩',emoji:'🍴',color:'#aabbcc',description:'친구와'};
  const created=await call('/books',{method:'POST',body:notebook});assert.equal(created.status,200);const id=created.body.id;
  assert.equal((await call('/books',{method:'POST',body:null})).status,400);
  assert.equal((await call('/books',{method:'POST',body:{...notebook,posts:[{rating:9}]}})).status,400);
  assert.equal((await call('/state')).body.books.length,1);
  assert.equal((await call('/books',{user:'',method:'POST',body:notebook})).status,401);
  assert.equal((await call('/books',{method:'POST',body:notebook,requestOrigin:'https://other.example'})).status,403);
  const invite=await call('/books/'+id+'/invites',{method:'POST',body:{}});const token=new URL(invite.body.url).searchParams.get('invite');assert.equal(token.length,48);
  assert.equal((await call('/invites/'+token,{user:''})).body.book.name,notebook.name);
  assert.equal((await call('/state',{user:'stranger'})).body.books.length,0);
  const entry={name:'같이 간 식당',area:'서울',category:'한식',rating:4.5,text:'맛있어요',date:'2026-10-21',photo:'',lat:37.5,lon:127};
  assert.equal((await call('/books/'+id+'/posts',{user:'stranger',method:'POST',body:entry})).status,404);
  assert.equal((await call('/invites/'+token+'/join',{user:'friend',method:'POST',body:{}})).status,200);
  await call('/invites/'+token+'/join',{user:'friend',method:'POST',body:{}});
  const memberState=await call('/state',{user:'friend'});assert.equal(memberState.body.books[0].members.length,2);assert.equal(memberState.body.books[0].role,'member');
  assert.equal((await call('/books/'+id,{user:'friend',method:'PATCH',body:{...notebook,version:2}})).status,403);
  assert.equal((await call('/books/'+id+'/invites',{user:'friend',method:'POST',body:{}})).status,403);
  const written=await call('/books/'+id+'/posts',{user:'friend',method:'POST',body:{...entry,authorId:'owner'}});const postId=written.body.id;
  let shared=await call('/state');assert.equal(shared.body.posts[0].authorId,'friend');assert.equal(shared.body.posts[0].author,'친구');
  assert.equal((await call('/posts/'+postId,{method:'PATCH',body:{...entry,version:1}})).status,403);
  assert.equal((await call('/posts/'+postId,{user:'friend',method:'PATCH',body:{...entry,text:'수정한 기록',version:1}})).status,200);
  assert.equal((await call('/posts/'+postId,{user:'friend',method:'PATCH',body:{...entry,text:'오래된 수정',version:1}})).status,409);
  const comment=await call('/posts/'+postId+'/comments',{method:'POST',body:{text:'다음에 또 가자'}});const commentId=comment.body.id;
  assert.equal((await call('/posts/'+postId+'/comments/'+commentId,{user:'friend',method:'DELETE',body:{version:1}})).status,403);
  assert.equal((await call('/posts/'+postId+'/comments/'+commentId,{method:'PATCH',body:{text:'다음 주에 또 가자',version:1}})).status,200);
  await call('/posts/'+postId+'/favorite',{method:'POST',body:{saved:true}});
  assert.equal((await call('/state')).body.posts[0].favorite,true);
  assert.equal((await call('/state',{user:'friend'})).body.posts[0].favorite,false);
  await Promise.all([call('/books/'+id+'/posts',{method:'POST',body:entry}),call('/books/'+id+'/posts',{user:'friend',method:'POST',body:entry})]);
  assert.equal((await call('/state')).body.posts.length,3);
  const disk=await readFile(file,'utf8');assert.ok(!disk.includes(token));
  const reloaded=await new CollaborationStore(file).load(),restartApi=createCollaborationApi({store:reloaded,getUser:req=>users[req.headers.user],origin,now:()=>clock});
  assert.equal((await call('/state',{handler:restartApi})).body.posts.length,3);
  assert.equal((await call('/state',{handler:restartApi})).body.posts.find(p=>p.id===postId).comments[0].text,'다음 주에 또 가자');
  await call('/books/'+id+'/invites',{method:'DELETE',body:{}});
  assert.equal((await call('/invites/'+token)).status,404);
  const next=await call('/books/'+id+'/invites',{method:'POST',body:{}}),nextToken=new URL(next.body.url).searchParams.get('invite');
  clock+=8*86400000;assert.equal((await call('/invites/'+nextToken)).status,404);
  await call('/books/'+id+'/members/friend',{method:'DELETE',body:{}});
  assert.equal((await call('/state',{user:'friend'})).body.posts.length,0);
  assert.equal((await call('/posts/'+postId+'/comments',{user:'friend',method:'POST',body:{text:'차단되어야 함'}})).status,404);
  console.log('PASS: two-user invite/join/coauthor, author permissions, isolation, conflicts, bookmarks, concurrent persistence, restart, expiry, revocation and removal');
}finally{await rm(directory,{recursive:true,force:true});}
